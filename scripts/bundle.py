#!/usr/bin/env python3
"""
scripts/bundle.py
Bundles the modules in src/modules/ (NN-name.js, in number order) into
payload/install-files/atlas.js, and makes the standalone
components/atlas/atlas-spelling.js from the spelling module.

    python3 scripts/bundle.py              write both files into the payload
    python3 scripts/bundle.py --out DIR    write them into DIR instead
    python3 scripts/bundle.py --check      exit 1 if the payload copies are out of date

Every module must stay at or under 350 lines. Output uses CRLF line endings.
The extension id comes from payload/detractless/src/constants/atlasKeys.json and
is written into atlas.js as ATLAS_EXT_ID / ATLAS_NEWTAB_URL.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

MAX_LINES_PER_MODULE = 350
ROOT = Path(__file__).resolve().parent.parent
MODULES_DIR = ROOT / "src" / "modules"
KEYS_JSON = ROOT / "payload" / "detractless" / "src" / "constants" / "atlasKeys.json"
ATLAS_JS = ROOT / "payload" / "install-files" / "atlas.js"
SPELLING_JS = ROOT / "payload" / "install-files" / "components" / "atlas" / "atlas-spelling.js"
CTXMENU_JS = ROOT / "payload" / "install-files" / "components" / "atlas" / "atlas-ctxmenu.js"
MODULE_RE = re.compile(r"^(\d{2})-.*\.js$")


def module_files():
    files = [p for p in MODULES_DIR.iterdir() if p.is_file() and MODULE_RE.match(p.name)]
    if not files:
        sys.exit(f"Error: no modules matching NN-*.js in {MODULES_DIR}")
    return sorted(files, key=lambda p: int(MODULE_RE.match(p.name).group(1)))


def size_violations(files):
    out = []
    for f in files:
        n = len(f.read_text(encoding="utf-8").splitlines())
        status = "OK" if n <= MAX_LINES_PER_MODULE else "EXCEEDS LIMIT"
        print(f"  [{status:13s}] {f.name:30s} ({n:3d} lines / max {MAX_LINES_PER_MODULE})")
        if n > MAX_LINES_PER_MODULE:
            out.append((f.name, n))
    return out


def crlf(text):
    return text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")


def header():
    keys = json.loads(KEYS_JSON.read_text(encoding="utf-8"))
    ext_id, page = keys["extensionId"], keys["newTabPath"]
    return (
        "/* Atlas mod for Vivaldi — bundled from src/modules/\n"
        "   Do not edit this file directly; edit src/modules/*.js and run scripts/bundle.py. */\n"
        "(function () {\n"
        "  'use strict';\n\n"
        "  var Atlas = window.__Atlas = window.__Atlas || {};\n"
        f"  var ATLAS_EXT_ID = '{ext_id}';\n"
        f"  var ATLAS_NEWTAB_URL = 'chrome-extension://{ext_id}/{page}';\n"
    )


def build_atlas(files):
    parts = [header()]
    for f in files:
        content = f.read_text(encoding="utf-8")
        parts.append(f"\n  /* ═══ Module: {f.name} ═══ */\n")
        parts.append(content if content.endswith("\n") else content + "\n")
    parts.append("\n})();\n")
    return crlf("".join(parts))


def build_spelling(files):
    src = next((f for f in files if f.name.endswith("-spelling.js")), None)
    if not src:
        return None
    raw = src.read_text(encoding="utf-8")
    rest = raw[raw.find("(function ()"):] if "(function ()" in raw else raw
    return crlf("/* ── atlas-spelling.js: Standalone offline spelling engine component ── */\n" + rest)


def validate_syntax(paths):
    node = shutil.which("node")
    if not node:
        print("Notice: node not found; skipping syntax validation.")
        return
    for target in paths:
        if not target.is_file():
            continue
        res = subprocess.run([node, "--check", str(target)], capture_output=True, text=True)
        if res.returncode != 0:
            print(f"Syntax validation FAILED for {target.name}:\n{res.stderr}", file=sys.stderr)
            sys.exit(res.returncode)
    print("Syntax validation PASSED (node --check).")


def write_outputs(out_dir):
    """Build into out_dir (None = the payload). Returns {name: path}."""
    files = module_files()
    print(f"Bundling {len(files)} modules from {MODULES_DIR.relative_to(ROOT)}:")
    bad = size_violations(files)
    if bad:
        for name, n in bad:
            print(f"  - {name}: {n} lines (exceeds {MAX_LINES_PER_MODULE})", file=sys.stderr)
        sys.exit(1)
    atlas_dst = (out_dir / ATLAS_JS.name) if out_dir else ATLAS_JS
    spelling_dst = (out_dir / SPELLING_JS.name) if out_dir else SPELLING_JS
    outputs = {"atlas.js": atlas_dst}
    atlas_dst.parent.mkdir(parents=True, exist_ok=True)
    atlas_dst.write_bytes(build_atlas(files).encode("utf-8"))
    spelling = build_spelling(files)
    if spelling is not None:
        spelling_dst.parent.mkdir(parents=True, exist_ok=True)
        spelling_dst.write_bytes(spelling.encode("utf-8"))
        outputs["atlas-spelling.js"] = spelling_dst
    validate_syntax([atlas_dst, spelling_dst, CTXMENU_JS])
    return outputs


def check():
    """True when the payload's atlas.js and atlas-spelling.js equal a fresh build."""
    with tempfile.TemporaryDirectory() as tmp:
        built = write_outputs(Path(tmp))
        shipped = {"atlas.js": ATLAS_JS, "atlas-spelling.js": SPELLING_JS}
        stale = [n for n, p in built.items() if p.read_bytes() != shipped[n].read_bytes()]
    for name in stale:
        print(f"OUT OF DATE: {name} (run python3 scripts/bundle.py)", file=sys.stderr)
    return not stale


def main(argv=None):
    ap = argparse.ArgumentParser(description="Bundle src/modules into atlas.js.")
    ap.add_argument("--out", type=Path, help="write into this folder instead of the payload")
    ap.add_argument("--check", action="store_true", help="only report whether the payload is up to date")
    args = ap.parse_args(argv)
    if args.check:
        sys.exit(0 if check() else 1)
    outputs = write_outputs(args.out)
    for name, path in outputs.items():
        print(f"Wrote {name}: {path}")


if __name__ == "__main__":
    main()
