#!/usr/bin/env python3
"""
scripts/bundle.py
Bundles modular JS sources in src/modules/ into payload/install-files/atlas.js.
Enforces <= 350 line limit per module and 100% Windows CRLF line endings.
Validates bundled syntax using `node -c`.
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

MAX_LINES_PER_MODULE = 350

def main():
    repo_root = Path(__file__).resolve().parent.parent
    modules_dir = repo_root / "src" / "modules"
    output_file = repo_root / "payload" / "install-files" / "atlas.js"

    if not modules_dir.is_dir():
        print(f"Error: Modules directory not found: {modules_dir}", file=sys.stderr)
        sys.exit(1)

    module_pattern = re.compile(r"^(\d{2})-.*\.js$")
    module_files = sorted(
        [p for p in modules_dir.iterdir() if p.is_file() and module_pattern.match(p.name)],
        key=lambda p: int(module_pattern.match(p.name).group(1))
    )

    if not module_files:
        print(f"Error: No modules matching pattern '##-*.js' found in {modules_dir}", file=sys.stderr)
        sys.exit(1)

    print(f"Discovered {len(module_files)} modules in {modules_dir.relative_to(repo_root)}:")

    violations = []
    bundle_parts = []

    # Outer IIFE opening with shared window.__Atlas / Atlas namespace
    header = (
        "/* Atlas mod for Vivaldi — bundled from src/modules/\n"
        "   Do not edit this file directly; edit src/modules/*.js and run build.cmd. */\n"
        "(function () {\n"
        "  'use strict';\n\n"
        "  var Atlas = window.__Atlas = window.__Atlas || {};\n"
    )
    bundle_parts.append(header)

    for mf in module_files:
        content = mf.read_text(encoding="utf-8")
        lines = content.splitlines()
        line_count = len(lines)
        status = "OK" if line_count <= MAX_LINES_PER_MODULE else "EXCEEDS LIMIT"
        print(f"  [{status:13s}] {mf.name:28s} ({line_count:3d} lines / max {MAX_LINES_PER_MODULE})")

        if line_count > MAX_LINES_PER_MODULE:
            violations.append((mf.name, line_count))

        # Add section banner and module content
        banner = f"\n  /* ═══ Module: {mf.name} ═══ */\n"
        bundle_parts.append(banner)
        bundle_parts.append(content)
        if not content.endswith("\n"):
            bundle_parts.append("\n")

    if violations:
        print("\nLine count limit violations detected:", file=sys.stderr)
        for name, count in violations:
            print(f"  - {name}: {count} lines (exceeds {MAX_LINES_PER_MODULE})", file=sys.stderr)
        sys.exit(1)

    # Outer IIFE closing
    footer = "\n})();\n"
    bundle_parts.append(footer)

    full_bundle = "".join(bundle_parts)

    # Normalize to CRLF (\r\n) line endings
    crlf_bundle = full_bundle.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")

    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "wb") as f:
        f.write(crlf_bundle.encode("utf-8"))

    total_lines = crlf_bundle.count("\r\n")
    print(f"\nSuccessfully bundled {len(module_files)} modules into {output_file.relative_to(repo_root)}")
    print(f"Total bundled lines: {total_lines} (CRLF)")

    # Sync standalone atlas-spelling.js from 12-spelling.js
    spelling_src = modules_dir / "12-spelling.js"
    spelling_dst = repo_root / "payload" / "install-files" / "components" / "atlas" / "atlas-spelling.js"
    if spelling_src.is_file():
        raw = spelling_src.read_text(encoding="utf-8")
        header = "/* ── atlas-spelling.js: Standalone offline spelling engine component ── */\n"
        rest = raw[raw.find("(function ()"):] if "(function ()" in raw else raw
        sp_crlf = (header + rest).replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
        spelling_dst.parent.mkdir(parents=True, exist_ok=True)
        with open(spelling_dst, "wb") as f:
            f.write(sp_crlf.encode("utf-8"))
        print(f"Synchronized standalone spelling component: {spelling_dst.relative_to(repo_root)}")

    # Validate syntax via node -c (or macOS jsc)
    files_to_validate = [
        output_file,
        spelling_dst,
        repo_root / "payload" / "install-files" / "components" / "atlas" / "atlas-ctxmenu.js"
    ]
    node_bin = shutil.which("node")
    jsc_candidate = Path("/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc")
    jsc_bin = str(jsc_candidate) if jsc_candidate.is_file() else shutil.which("jsc")

    if node_bin:
        print("Validating syntax with `node -c`...")
        for target in files_to_validate:
            if not target.is_file():
                continue
            res = subprocess.run([node_bin, "-c", str(target)], capture_output=True, text=True)
            if res.returncode != 0:
                print(f"Syntax validation FAILED for {target.name} (exit code {res.returncode}):", file=sys.stderr)
                print(res.stderr, file=sys.stderr)
                sys.exit(res.returncode)
        print("Syntax validation PASSED (node -c returned 0 for all scripts).")
    elif jsc_bin:
        print("Validating syntax with JavaScriptCore (`jsc`)...")
        for target in files_to_validate:
            if not target.is_file():
                continue
            res = subprocess.run([jsc_bin, "-e", f"checkSyntax({json.dumps(str(target))});"], capture_output=True, text=True)
            if res.returncode != 0:
                print(f"Syntax validation FAILED for {target.name} (exit code {res.returncode}):", file=sys.stderr)
                print(res.stderr, file=sys.stderr)
                sys.exit(res.returncode)
        print("Syntax validation PASSED (jsc checkSyntax returned 0 for all scripts).")
    else:
        print("Notice: neither `node` nor `jsc` found; skipping syntax validation.")

if __name__ == "__main__":
    main()
