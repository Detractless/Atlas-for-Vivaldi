  /* Fast static buffer for Damerau-Levenshtein calculation (avoids allocations) */
  var MAT = new Int32Array(32 * 32);

  function damerauLevenshtein(a, b) {
    var al = a.length, bl = b.length;
    if (Math.abs(al - bl) > 2) return 999;
    if (al === 0) return bl;
    if (bl === 0) return al;
    if (al > 31 || bl > 31) return 999;

    var stride = 32;
    for (var i = 0; i <= al; i++) MAT[i * stride] = i;
    for (var j = 0; j <= bl; j++) MAT[j] = j;

    for (var i = 1; i <= al; i++) {
      var ca = a.charCodeAt(i - 1);
      var row = i * stride;
      var prevRow = (i - 1) * stride;
      var pprevRow = (i - 2) * stride;
      for (var j = 1; j <= bl; j++) {
        var cost = (ca === b.charCodeAt(j - 1)) ? 0 : 1;
        var del = MAT[prevRow + j] + 1;
        var ins = MAT[row + j - 1] + 1;
        var sub = MAT[prevRow + j - 1] + cost;
        var m = del < ins ? del : ins;
        if (sub < m) m = sub;

        if (i > 1 && j > 1 && ca === b.charCodeAt(j - 2) && a.charCodeAt(i - 2) === b.charCodeAt(j - 1)) {
          var trans = MAT[pprevRow + j - 2] + 1;
          if (trans < m) m = trans;
        }
        MAT[row + j] = m;
      }
    }
    return MAT[al * stride + bl];
  }

